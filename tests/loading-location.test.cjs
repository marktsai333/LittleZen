const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('candidate/littleZen.uc.js', 'utf8');
const start = source.indexOf('  function releaseLittleWindowOnCommittedLocation(');
const end = source.indexOf('  function attachEmptyTabStateTracking(', start);
assert.ok(start >= 0 && end > start);
const calls = [];
const context = { isLittleWindow: w => w.little, setLittleWindowLoading: (...args) => calls.push(args) };
vm.runInNewContext(source.slice(start, end) + '\nthis.run = releaseLittleWindowOnCommittedLocation;', context);
const browser = {};
const win = { little: true, document: { documentElement: { hasAttribute: () => true } }, gBrowser: { selectedBrowser: browser } };
const progress = { isTopLevel: true };
const location = { spec: 'https://example.invalid/' };
assert.equal(context.run(win, browser, progress, location), true);
assert.equal(calls.length, 1);
assert.equal(calls[0][1], false);
assert.equal(calls[0][2], 'location-committed');
win.__littleZenPendingURL = 'https://example.invalid/';
assert.equal(context.run(win, browser, progress, location), false);
delete win.__littleZenPendingURL;
assert.equal(context.run(win, browser, progress, { spec: 'about:blank' }), false);
assert.equal(context.run(win, {}, progress, location), false);
assert.equal(context.run(win, browser, { isTopLevel: false }, location), false);
win.little = false;
assert.equal(context.run(win, browser, progress, location), false);
assert.equal(calls.length, 1);
assert.ok(source.includes('releaseLittleWindowOnCommittedLocation(win, browser, webProgress, locationURI);'));
console.log('Only a committed top-level location in the selected Little Zen browser releases the loading cover.');
