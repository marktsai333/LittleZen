const assert = require('node:assert/strict');
const fs = require('node:fs');
const css = fs.readFileSync('candidate/little-zen.css', 'utf8');
const js = fs.readFileSync('candidate/littleZen.uc.js', 'utf8');
const rule = css.match(/:root\[zen-little-window="true"\]\[little-zen-can-go-back="true"\]:not\(\[zen-has-empty-tab="true"\]\) #nav-bar #back-button\s*\{([^}]*)\}/);
assert.ok(rule, 'back button is visible only in the loaded Little Zen window');
assert.match(rule[1], /display:\s*flex\s*!important/);
assert.match(rule[1], /margin-inline:\s*0\s+6px/);
assert.doesNotMatch(rule[1], /list-style-image|data:image/);
assert.match(js, /for \(const id of \["back-button", "forward-button", "stop-reload-button"\]\)[\s\S]*?target\.insertBefore\(item, urlbar\)/);
const vm = require('node:vm');
const start = js.indexOf('  function syncLittleZenBackAvailability(');
const end = js.indexOf('  function attachEmptyTabStateTracking(', start);
assert.ok(start >= 0 && end > start);
const attrs = {};
const root = { setAttribute(k, v) { attrs[k] = v; }, removeAttribute(k) { delete attrs[k]; } };
const win = { document: { documentElement: root }, gBrowser: { selectedBrowser: { canGoBack: false } } };
const context = { isLittleWindow: () => true };
vm.runInNewContext(js.slice(start, end) + '\nthis.sync = syncLittleZenBackAvailability;', context);
context.sync(win);
assert.equal(attrs['little-zen-can-go-back'], undefined);
win.gBrowser.selectedBrowser.canGoBack = true;
context.sync(win);
assert.equal(attrs['little-zen-can-go-back'], 'true');
win.gBrowser.selectedBrowser.canGoBack = false;
context.sync(win);
assert.equal(attrs['little-zen-can-go-back'], undefined);
console.log('The existing Back control keeps Zen’s icon and is placed before the URL bar.');
