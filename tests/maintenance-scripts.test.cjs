const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const source = path.resolve('.');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'littlezen-maintenance-'));
try {
  const root = path.join(tmp, 'project');
  const profile = path.join(tmp, 'profile');
  const hs = path.join(tmp, 'hammerspoon');
  for (const dir of ['scripts', 'candidate', 'backups']) fs.mkdirSync(path.join(root, dir), { recursive: true });
  for (const dir of ['chrome/CSS', 'chrome/JS', 'chrome/utils']) fs.mkdirSync(path.join(profile, dir), { recursive: true });
  fs.mkdirSync(hs);
  for (const file of ['install-current-profile.sh', 'rollback-current-profile.sh']) fs.copyFileSync(path.join(source, 'scripts', file), path.join(root, 'scripts', file));
  for (const file of ['little-zen.css', 'littleZen.uc.js', 'little-zen-bridge.lua']) fs.copyFileSync(path.join(source, 'candidate', file), path.join(root, 'candidate', file));
  const put = (p, value) => fs.writeFileSync(p, value);
  const css = path.join(profile, 'chrome/CSS/little-zen.css');
  const js = path.join(profile, 'chrome/JS/littleZen.uc.js');
  const user = path.join(profile, 'user.js');
  const init = path.join(hs, 'init.lua');
  const bridge = path.join(hs, 'little-zen-bridge.lua');
  put(css, 'old css'); put(js, 'old js'); put(user, 'other user settings');
  put(path.join(profile, 'chrome/userChrome.css'), '@import url("CSS/little-zen.css");\n');
  put(path.join(profile, 'chrome/utils/boot.sys.mjs'), 'loader');
  put(init, 'custom init and little-zen-bridge.lua');
  fs.copyFileSync(path.join(root, 'candidate/little-zen-bridge.lua'), bridge);
  const env = { ...process.env, LITTLE_ZEN_PROFILE: profile, LITTLE_ZEN_HAMMERSPOON_DIR: hs };
  const run = (script, args = []) => spawnSync('sh', [path.join(root, 'scripts', script), ...args], { env, encoding: 'utf8' });
  const installed = run('install-current-profile.sh');
  assert.equal(installed.status, 0, installed.stderr);
  assert.equal(fs.readFileSync(user, 'utf8'), 'other user settings');
  assert.equal(fs.readFileSync(init, 'utf8'), 'custom init and little-zen-bridge.lua');
  const backup = installed.stdout.match(/Backup: (.+)/)?.[1];
  assert.ok(backup);
  const restored = run('rollback-current-profile.sh', [backup]);
  assert.equal(restored.status, 0, restored.stderr);
  assert.equal(fs.readFileSync(css, 'utf8'), 'old css');
  assert.equal(fs.readFileSync(js, 'utf8'), 'old js');
  assert.equal(fs.readFileSync(init, 'utf8'), 'custom init and little-zen-bridge.lua');
  put(bridge, 'user-edited bridge');
  assert.equal(run('install-current-profile.sh').status, 2);
  assert.equal(fs.readFileSync(css, 'utf8'), 'old css');
  assert.equal(run('rollback-current-profile.sh', [backup]).status, 2);
  assert.equal(fs.readFileSync(js, 'utf8'), 'old js');
  console.log('Maintenance scripts preserve unrelated settings and refuse edited files.');
} finally { fs.rmSync(tmp, { recursive: true, force: true }); }
